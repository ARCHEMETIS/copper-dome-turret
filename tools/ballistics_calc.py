# ใช้ทำอะไร:
#   1) เป็น "รายการคำนวณการเคลื่อนที่กระสุน" — หัวข้อบังคับตอนนำเสนอ
#   2) ประเมินก่อนสร้างว่า มุมเงย/ความเร็วลูกช่วงไหนถึงยิงถึงเป้า 1.5-2 m
#   3) วันจูนจริง ใช้เทียบว่าตาราง PWM↔ระยะที่วัดได้ สมเหตุสมผลไหม
#
# โมเดล: จุดปล่อยลูกสูง h0 จากพื้น, เป้าสูง h1, มุมเงย θ, ความเร็วต้น v
#   x(t) = v·cosθ·t
#   y(t) = h0 + v·sinθ·t − ½g·t²
# แก้สมการหา x ที่ y = h1 (เลือกรากขาลง = ลูกกำลังตก)
#
# หมายเหตุความจริง: ลูกบอลไม้มีแรงต้านอากาศ + ล้อถ่ายพลังงานไม่ 100%
# → ตัวเลขนี้คือ "ทฤษฎีสำหรับสไลด์และการประเมิน" ความแม่นจริงมาจาก
#   การยิงวัดจริง (tools/calibrate_pwm.py) เสมอ — เขียนแบบนี้ในสไลด์ได้เลย
#   กรรมการชอบคนที่รู้ข้อจำกัดของโมเดลตัวเอง
# =============================================================
import math

G = 9.81            # m/s²
H_MUZZLE = 0.55     # ความสูงปากกระบอกจากพื้น (m): แท่น 0.4 + ตัวป้อม ~0.15 — แก้ตามจริง
H_TARGET = 0.85     # ความสูงกึ่งกลางเป้า (m): โต๊ะ 0.8 + ครึ่งตุ๊กตา ~0.05 — แก้ตามจริง
ANGLES_DEG = [20, 25, 30, 35]          # มุมเงยที่พิจารณา
SPEEDS = [4, 5, 6, 7, 8, 10, 12]       # ความเร็วลูก (m/s) ที่พิจารณา


def range_at(v: float, angle_deg: float) -> float | None:
    """ระยะราบ (m) ที่ลูกตกถึงระดับเป้า — None ถ้าไปไม่ถึงระดับเป้าเลย"""
    th = math.radians(angle_deg)
    vx, vy = v * math.cos(th), v * math.sin(th)
    dh = H_TARGET - H_MUZZLE
    disc = vy * vy - 2 * G * dh        # จากการแก้สมการกำลังสองของเวลา
    if disc < 0:
        return None                     # ขึ้นไม่ถึงความสูงเป้า
    t = (vy + math.sqrt(disc)) / G      # รากขาลง (ลูกกำลังตกผ่านระดับเป้า)
    return vx * t


def speed_for(distance_m: float, angle_deg: float) -> float | None:
    """ความเร็วต้น (m/s) ที่ต้องใช้เพื่อให้ตกที่ระยะ x — สูตรปิด"""
    th = math.radians(angle_deg)
    dh = H_TARGET - H_MUZZLE
    denom = 2 * math.cos(th) ** 2 * (distance_m * math.tan(th) - dh)
    if denom <= 0:
        return None                     # มุมนี้ยิงระยะนี้ไม่ได้ (เป้าสูงเกินแนว)
    return distance_m * math.sqrt(G / denom)


def main():
    print(f"จุดปล่อยสูง {H_MUZZLE} m | เป้าสูง {H_TARGET} m (Δh = {H_TARGET - H_MUZZLE:+.2f} m)\n")

    print("── ตาราง 1: ยิงด้วยความเร็ว v ที่มุม θ แล้วลูกตกไกลเท่าไร (m) ──")
    header = "v (m/s) |" + "".join(f"  θ={a}°" for a in ANGLES_DEG)
    print(header)
    print("-" * len(header))
    for v in SPEEDS:
        row = f"{v:7.1f} |"
        for a in ANGLES_DEG:
            r = range_at(v, a)
            row += f"  {r:5.2f}" if r else "    -- "
        print(row)

    print("\n── ตาราง 2: อยากให้ตกที่ระยะ x ต้องใช้ความเร็วเท่าไร (m/s) ──")
    dists = [1.0, 1.25, 1.5, 1.75, 2.0, 2.25]
    header = "x (m)   |" + "".join(f"  θ={a}°" for a in ANGLES_DEG)
    print(header)
    print("-" * len(header))
    for d in dists:
        row = f"{d:7.2f} |"
        for a in ANGLES_DEG:
            s = speed_for(d, a)
            row += f"  {s:5.2f}" if s else "    -- "
        print(row)

    print("""
วิธีอ่านผล:
- โจทย์ระยะ ~1.5-2 m ต้องการความเร็วลูกแค่ ~4-6 m/s เท่านั้น (ไม่ต้องแรงมาก!)
- ⚠️ ดูตาราง 2 ที่ θ=25°: ความเร็ว "ไม่เรียงตามระยะ" (1.0m ใช้เร็วกว่า 1.5m)
  เพราะเป้าอยู่สูงกว่าปากกระบอก → ระยะเดียวได้จากความเร็ว 2 ค่า
  ตาราง PWM↔ระยะจะกำกวม interpolate พัง! ที่ θ=30-35° เรียงสวยตลอดช่วง
  → ควรล็อกมุมเงย ~30-35° (จุดขายตอนนำเสนอ: เลือกมุมจากการวิเคราะห์ ไม่ใช่เดา)
- ตอน calibrate จริง เช็คเสมอว่า duty มาก → ระยะไกลขึ้นเสมอ (monotonic)
- ความเร็วขอบล้อ ≈ 2× ความเร็วลูก (ลูกออกช้ากว่าผิวล้อ) → ล้อ Ø50mm
  ต้องหมุนราว (2×5 m/s)/(π×0.05) ≈ 64 รอบ/วินาที ≈ 3800 RPM → มอเตอร์ 130/280
  แบบเปลือยถึงต้องหมุนเร็ว และ TT motor มีเกียร์ (~200RPM) ถึงใช้ไม่ได้!
""")


if __name__ == "__main__":
    main()
